import json

def clean_jupyter_notebook(input_file, output_file):
    # Load the corrupted notebook
    with open(input_file, 'r', encoding='utf-8') as f:
        notebook = json.load(f)

    for cell in notebook.get('cells', []):
        # We only want to clean the source code and markdown text
        if cell.get('cell_type') in ['code', 'markdown']:
            new_source = []
            
            for text in cell.get('source', []):
                # 1. Fix Inline Duplication: Find the shortest repeating string unit
                length = len(text)
                for i in range(1, length // 2 + 1):
                    if length % i == 0:
                        chunk = text[:i]
                        # If the line is just the chunk repeated multiple times, compress it
                        if chunk * (length // i) == text:
                            text = chunk
                            break
                
                # 2. Fix Sequential Duplication: Prevent appending identical consecutive lines
                if not new_source or text != new_source[-1]:
                    new_source.append(text)
                    
            # 3. Clean up excessive consecutive blank lines generated by deduplication
            filtered_source = []
            for text in new_source:
                if text == '\n' and filtered_source and filtered_source[-1] == '\n':
                    continue
                filtered_source.append(text)
                
            # Replace the old corrupted source with the cleaned text
            cell['source'] = filtered_source

    # Save the cleaned notebook
    with open(output_file, 'w', encoding='utf-8') as f:
        json.dump(notebook, f, indent=1)
        print(f"Successfully cleaned notebook! Saved to: {output_file}")

